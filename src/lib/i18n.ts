export type MessageKey = keyof (typeof messages)["zh"];

export function translate(locale: Locale, key: MessageKey): string {
  return messages[locale][key] ?? messages.zh[key];
}

export function translateKnownValue(locale: Locale, value: string): string {
  if (value in messages.zh) {
    return translate(locale, value as MessageKey);
  }
  return value;
}

export function categoryLabel(locale: Locale, category: string): string {
  const key = `category.${category}` as MessageKey;
  return key in messages.zh ? translate(locale, key) : category;
}

export function riskLabel(locale: Locale, risk: string): string {
  const key = `risk.${risk}` as MessageKey;
  return key in messages.zh ? translate(locale, key) : risk;
}

export function detectionLabel(locale: Locale, detection: string): string {
  const key = `detection.${detection}` as MessageKey;
  return key in messages.zh ? translate(locale, key) : detection;
}
